#!/usr/bin/env python3
"""Generate a simple low-poly Hyundai Nexo (1st gen) style SUV for the cluster HUD.

Hand-built from public dimensions (4,670 x 1,860 x 1,630 mm, wheelbase 2,790 mm);
no third-party mesh is used. Output follows the cybertruck model contract:
x = vehicle right, y = vehicle forward, z = up, bounds normalized to 1 x 1 x 1
(x/y in -0.5..0.5, z in 0..1). Materials reuse names already colored by the renderer.

    python make_nexo_model.py        # writes nexo_cluster.obj next to this file
"""
import math
from pathlib import Path

OUT = Path(__file__).with_name("nexo_cluster.obj")
BODY = "nexo_white"   # body paint material (white car)
ROOF_SCALE = 0.75    # greenhouse height relative to the original 1.0 roof (lower = sportier)
GROUND = 0.105          # ride height / body height (normalized)
WHEELBASE = 2.79 / 4.67
WHEEL_R = 0.37 / 1.63   # 0.74 m tyre diameter / height


class Obj:
    def __init__(self):
        self.v: list[tuple[float, float, float]] = []
        self.groups: list[tuple[str, list[tuple[int, ...]]]] = []

    def add_v(self, p):
        self.v.append(p)
        return len(self.v)

    def face(self, material, idx, ref):
        """Add a polygon, flipping it so its normal points away from ref."""
        pts = [self.v[i - 1] for i in idx]
        ax, ay, az = pts[0]
        bx, by, bz = pts[1]
        cx, cy, cz = pts[2]
        n = ((by - ay) * (cz - az) - (bz - az) * (cy - ay),
             (bz - az) * (cx - ax) - (bx - ax) * (cz - az),
             (bx - ax) * (cy - ay) - (by - ay) * (cx - ax))
        c = [sum(p[k] for p in pts) / len(pts) for k in range(3)]
        if sum(n[k] * (c[k] - ref[k]) for k in range(3)) < 0:
            idx = tuple(reversed(idx))
            n = tuple(-x for x in n)
        if material == "cabin":
            # greenhouse: roof panel and the rear (D) pillars in body colour so the roof is
            # visibly tied to the body; side windows and the tailgate glass stay dark
            length = math.sqrt(sum(x * x for x in n)) or 1.0
            nx, ny, nz = (x / length for x in n)
            roof = nz > 0.9
            d_pillar_side = abs(nx) > 0.55 and c[1] < -0.33
            glass_frame = ny < -0.45 and abs(c[0]) > 0.285
            material = BODY if roof or d_pillar_side or glass_frame else "Material.002"
        if not self.groups or self.groups[-1][0] != material:
            self.groups.append((material, []))
        self.groups[-1][1].append(tuple(idx))

    def write(self, path):
        lines = ["# Low-poly Hyundai Nexo style SUV for raylib cluster rendering (generated by make_nexo_model.py).",
                 "# Local axes: x=vehicle right, y=vehicle forward, z=vehicle up. Bounds normalized to 1 x 1 x 1.",
                 "mtllib nexo_cluster.mtl", ""]
        lines += [f"v {x:.5f} {y:.5f} {z:.5f}" for x, y, z in self.v]
        for material, faces in self.groups:
            lines.append(f"usemtl {material}")
            lines += ["f " + " ".join(map(str, f)) for f in faces]
        path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def section(half_w, bottom, top, top_half_w, radius, y, steps=4):
    """Rounded trapezoid cross-section (closed loop) at station y."""
    r = min(radius, (top - bottom) * 0.45, top_half_w * 0.9)
    pts = []
    # bottom edge -> right side -> top -> left side (counter-clockwise seen from behind)
    pts.append((-half_w + r * 0.3, y, bottom))
    pts.append((half_w - r * 0.3, y, bottom))
    for k in range(steps + 1):   # right upper corner
        a = k / steps * math.pi / 2
        pts.append((top_half_w - r + r * math.cos(a), y, top - r + r * math.sin(a)))
    for k in range(steps + 1):   # left upper corner
        a = math.pi / 2 + k / steps * math.pi / 2
        pts.append((-top_half_w + r + r * math.cos(a), y, top - r + r * math.sin(a)))
    pts.insert(2, (half_w, y, bottom + (top - bottom) * 0.35))
    pts.append((-half_w, y, bottom + (top - bottom) * 0.35))
    return pts


def loft(obj, sections, material, ref_z, cap_materials=(None, None), side_material=None):
    rings = [[obj.add_v(p) for p in s] for s in sections]
    n = len(rings[0])
    for a, b in zip(rings, rings[1:]):
        for i in range(n):
            j = (i + 1) % n
            pa = obj.v[a[i] - 1]
            ref = (0.0, pa[1], ref_z)
            obj.face(side_material(i, n) if side_material else material, (a[i], a[j], b[j], b[i]), ref)
    for ring, mat in ((rings[0], cap_materials[0]), (rings[-1], cap_materials[1])):
        if mat:
            y = obj.v[ring[0] - 1][1]
            center = obj.add_v((0.0, y, ref_z))
            for i in range(n):
                obj.face(mat, (center, ring[i], ring[(i + 1) % n]), (0.0, 0.0, ref_z))


def box(obj, material, x0, x1, y0, y1, z0, z1):
    p = [obj.add_v((x, y, z)) for z in (z0, z1) for y in (y0, y1) for x in (x0, x1)]
    ref = ((x0 + x1) / 2, (y0 + y1) / 2, (z0 + z1) / 2)
    for quad in ((0, 1, 3, 2), (4, 5, 7, 6), (0, 1, 5, 4), (2, 3, 7, 6), (0, 2, 6, 4), (1, 3, 7, 5)):
        obj.face(material, tuple(p[i] for i in quad), ref)


def prism(obj, material, poly_xz, y0, y1):
    """Extrude a convex x/z polygon between y0 and y1 (used for the chevron tail lamps)."""
    back = [obj.add_v((x, y0, z)) for x, z in poly_xz]
    front = [obj.add_v((x, y1, z)) for x, z in poly_xz]
    cx = sum(x for x, _ in poly_xz) / len(poly_xz)
    cz = sum(z for _, z in poly_xz) / len(poly_xz)
    ref = (cx, (y0 + y1) / 2, cz)
    obj.face(material, tuple(back), ref)
    obj.face(material, tuple(front), ref)
    for i in range(len(poly_xz)):
        j = (i + 1) % len(poly_xz)
        obj.face(material, (back[i], back[j], front[j], front[i]), ref)


def wheel(obj, x_center, y_center, width, segments=20):
    ring_out, ring_in, hub = [], [], []
    xo, xi = x_center + width / 2 * (1 if x_center > 0 else -1), x_center - width / 2 * (1 if x_center > 0 else -1)
    for k in range(segments):
        a = 2 * math.pi * k / segments
        y, z = y_center + WHEEL_R * math.cos(a), WHEEL_R + WHEEL_R * math.sin(a)
        ring_out.append(obj.add_v((xo, y, z)))
        ring_in.append(obj.add_v((xi, y, z)))
        hub.append(obj.add_v((xo + 0.002 * (1 if x_center > 0 else -1),
                              y_center + WHEEL_R * 0.62 * math.cos(a), WHEEL_R + WHEEL_R * 0.62 * math.sin(a))))
    ref = (x_center, y_center, WHEEL_R)
    for k in range(segments):
        j = (k + 1) % segments
        obj.face("wheel", (ring_out[k], ring_out[j], ring_in[j], ring_in[k]), ref)
    c_out = obj.add_v((xo, y_center, WHEEL_R))
    c_hub = obj.add_v((xo + 0.003 * (1 if x_center > 0 else -1), y_center, WHEEL_R))
    for k in range(segments):
        j = (k + 1) % segments
        obj.face("wheel", (c_out, ring_out[k], ring_out[j]), (x_center - (xo - x_center) * 4, y_center, WHEEL_R))
        obj.face("besi_roda", (c_hub, hub[k], hub[j]), (x_center - (xo - x_center) * 4, y_center, WHEEL_R))


def build():
    obj = Obj()
    # Lower body: stations from rear (-0.5) to front (+0.5): (y, half width, belt height).
    # Wide rear haunches over the back wheels, tapering tail, high belt line.
    body_stations = [
        (-0.500, 0.420, 0.625), (-0.494, 0.455, 0.640), (-0.478, 0.485, 0.645), (-0.440, 0.502, 0.640),
        (-0.330, 0.510, 0.628), (-0.150, 0.497, 0.610), (0.100, 0.492, 0.590), (0.280, 0.500, 0.568),
        (0.400, 0.492, 0.530), (0.470, 0.470, 0.488), (0.500, 0.425, 0.452),
    ]

    def belt_at(y):
        for (y0, _, b0), (y1, _, b1) in zip(body_stations, body_stations[1:]):
            if y0 <= y <= y1:
                return b0 + (b1 - b0) * (y - y0) / (y1 - y0)
        return body_stations[-1][2]

    sections = [section(w, GROUND, belt, w * 0.96, 0.09, y) for y, w, belt in body_stations]
    loft(obj, sections, BODY, (GROUND + 0.6) / 2, cap_materials=(BODY, BODY))

    # Greenhouse, much narrower than the body (strong shoulders), coupe-like falling roof
    # and a raked tailgate glass: (y, half width at belt, roof height, roof half width)
    cabin_stations = [
        (-0.452, 0.395, belt_at(-0.452) + 0.012, 0.360), (-0.415, 0.410, 0.780, 0.320),
        (-0.345, 0.420, 0.915, 0.300), (-0.250, 0.428, 0.975, 0.298), (-0.050, 0.433, 1.000, 0.302),
        (0.080, 0.433, 0.990, 0.300), (0.190, 0.428, 0.815, 0.325), (0.300, 0.415, belt_at(0.300) + 0.012, 0.380),
    ]
    def lower(z, belt=0.64):
        return belt + (z - belt) * ROOF_SCALE

    cab = [section(w, belt_at(y) - 0.012, max(lower(roof), belt_at(y) + 0.012), rw, 0.07, y, steps=3)
           for y, w, roof, rw in cabin_stations]
    loft(obj, cab, "cabin", 0.8, cap_materials=("Material.002", "Material.002"))

    # Black roof spoiler continuing the roof line over the tailgate glass, silver roof rails
    box(obj, "Material.003", -0.305, 0.305, -0.392, -0.330, lower(0.896), lower(0.922))
    for side in (-1, 1):
        x0, x1 = sorted((side * 0.262, side * 0.286))
        box(obj, "Material", x0, x1, -0.300, 0.060, lower(0.972), lower(1.000))

    # 1st-gen Nexo tail lamps: arrow-head (chevron) lamps on the upper corners, pointing inward,
    # wrapping round the corner. They do not connect; the tailgate between them is body colour.
    for side in (-1, 1):
        chevron = [(0.478, 0.612), (0.235, 0.598), (0.250, 0.582), (0.470, 0.505)]
        prism(obj, "stop_light", [(side * x, z) for x, z in chevron], -0.507, -0.478)
        inner = [(0.455, 0.600), (0.275, 0.592), (0.285, 0.586), (0.450, 0.560)]   # bright LED line
        prism(obj, "light", [(side * x, z) for x, z in inner], -0.509, -0.505)
        x0, x1 = sorted((side * 0.478, side * 0.493))   # wrap onto the side panel
        box(obj, "stop_light", x0, x1, -0.480, -0.430, 0.560, 0.608)
    box(obj, "Material", -0.034, 0.034, -0.505, -0.498, 0.505, 0.530)   # badge on the tailgate

    # Body-coloured rear bumper with a recessed licence plate, small low reflectors and silver skid trim
    box(obj, "Material.003", -0.132, 0.132, -0.504, -0.497, 0.262, 0.342)
    box(obj, "light", -0.118, 0.118, -0.506, -0.502, 0.270, 0.334)
    for side in (-1, 1):
        x0, x1 = sorted((side * 0.385, side * 0.440))
        box(obj, "stop_light", x0, x1, -0.505, -0.497, 0.165, 0.180)
    box(obj, "Material", -0.330, 0.330, -0.507, -0.494, GROUND + 0.012, 0.150)
    for side in (-1, 1):   # silver wedges toward the bumper corners
        prism(obj, "Material", [(side * 0.330, GROUND + 0.012), (side * 0.330, 0.150),
                                (side * 0.415, 0.205), (side * 0.405, GROUND + 0.04)], -0.505, -0.494)
    for side in (-1, 1):   # dark sill along the sides
        x0, x1 = sorted((side * 0.497, side * 0.509))
        box(obj, "Material.003", x0, x1, -0.36, 0.36, GROUND, 0.150)
    # Thin front lamp bar (visible from the side camera views)
    box(obj, "light", -0.42, 0.42, 0.492, 0.505, 0.455, 0.47)

    for x in (-0.445, 0.445):
        for y in (-WHEELBASE / 2, WHEELBASE / 2):
            wheel(obj, x, y, 0.13)
    # Wheels and lamps stick out slightly; rescale so the whole model fits the -0.5..0.5 contract
    sx = 0.5 / max(abs(p[0]) for p in obj.v)
    sy = 0.5 / max(abs(p[1]) for p in obj.v)
    obj.v = [(x * sx, y * sy, z) for x, y, z in obj.v]
    return obj


if __name__ == "__main__":
    model = build()
    model.write(OUT)
    xs, ys, zs = zip(*model.v)
    print(f"{OUT.name}: {len(model.v)} vertices, {sum(len(f) for _, f in model.groups)} faces, "
          f"x {min(xs):.3f}..{max(xs):.3f} y {min(ys):.3f}..{max(ys):.3f} z {min(zs):.3f}..{max(zs):.3f}")
